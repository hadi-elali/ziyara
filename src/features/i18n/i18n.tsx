const defaultContext: I18nContextValue = {
  isRTL: false,
  language: "de",
  loaded: false,
  setLanguage: () => undefined,
  t: (key, params) => translate("de", key, params),
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function translate(
  language: Language,
  key: string,
  params?: TranslationParams,
) {
  const template = dictionaries[language][key] ?? dictionaries.de[key] ?? key;

  if (!params) {
    return template;
  }

  return Object.entries(params).reduce(
    (text, [paramKey, value]) =>
      text.replaceAll(`{${paramKey}}`, String(value)),
    template,
  );
}

export function AppI18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguage, loaded] = useLanguageState();

  const value = useMemo<I18nContextValue>(
    () => ({
      isRTL: language === "ar",
      language,
      loaded,
      setLanguage,
      t: (key, params) => translate(language, key, params),
    }),
    [language, loaded, setLanguage],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
