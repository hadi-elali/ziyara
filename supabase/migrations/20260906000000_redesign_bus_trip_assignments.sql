create or replace function public.admin_copy_trip_bus_setup(
  p_source_trip_id int8,
  p_name text
)
returns public.trips
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_profile_id int8;
  copied_family_id int8;
  created_trip public.trips;
  leader_assignment public.trip_participants;
  leader_profile_id int8;
  saved_assignment public.trip_participants;
  source_assignment record;
  source_bus record;
  source_bus_ids int8[] := '{}'::int8[];
  target_bus_id int8;
  target_bus_ids int8[] := '{}'::int8[];
begin
  if (select auth.uid()) is null or not (select public.is_admin()) then
    raise exception 'Admin access required.' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(2026090600);

  if not exists (
    select 1
    from public.trips as trips
    where trips.id = p_source_trip_id
      and trips.archived_at is not null
  ) then
    raise exception 'Closed source trip not found.' using errcode = 'P0002';
  end if;

  select profiles.id
  into actor_profile_id
  from public.profiles as profiles
  where profiles.user_id = (select auth.uid());

  insert into public.trips (name, created_by_profile_id)
  values (btrim(p_name), actor_profile_id)
  returning * into created_trip;

  for source_bus in
    select buses.*
    from public.trip_buses as buses
    where buses.trip_id = p_source_trip_id
    order by buses.sort_order, buses.id
  loop
    insert into public.trip_buses (trip_id, name, sort_order)
    values (created_trip.id, source_bus.name, source_bus.sort_order)
    returning id into target_bus_id;

    source_bus_ids := array_append(source_bus_ids, source_bus.id);
    target_bus_ids := array_append(target_bus_ids, target_bus_id);
  end loop;

  for source_assignment in
    select distinct on (participants.profile_id)
      participants.assignment_family_id,
      participants.bus_id,
      participants.profile_id
    from public.trip_participants as participants
    where participants.trip_id = p_source_trip_id
      and participants.profile_id is not null
      and participants.bus_id is not null
    order by
      participants.profile_id,
      participants.updated_at desc,
      participants.id desc
  loop
    target_bus_id := target_bus_ids[array_position(source_bus_ids, source_assignment.bus_id)];
    if target_bus_id is null then
      continue;
    end if;

    select case
      when profiles.family_id = source_assignment.assignment_family_id
        then source_assignment.assignment_family_id
      else null
    end
    into copied_family_id
    from public.profiles as profiles
    where profiles.id = source_assignment.profile_id;

    select *
    into saved_assignment
    from public.ensure_trip_profile_bus_assignment(
      created_trip.id,
      target_bus_id,
      source_assignment.profile_id,
      copied_family_id
    );
  end loop;

  for source_bus in
    select buses.*
    from public.trip_buses as buses
    where buses.trip_id = p_source_trip_id
      and buses.leader_participant_id is not null
    order by buses.sort_order, buses.id
  loop
    select participants.profile_id
    into leader_profile_id
    from public.trip_participants as participants
    where participants.id = source_bus.leader_participant_id;

    if leader_profile_id is null then
      continue;
    end if;

    target_bus_id := target_bus_ids[array_position(source_bus_ids, source_bus.id)];

    select participants.assignment_family_id
    into copied_family_id
    from public.trip_participants as participants
    where participants.trip_id = created_trip.id
      and participants.profile_id = leader_profile_id
    order by participants.updated_at desc, participants.id desc
    limit 1;

    select *
    into leader_assignment
    from public.ensure_trip_profile_bus_assignment(
      created_trip.id,
      target_bus_id,
      leader_profile_id,
      copied_family_id
    );

    update public.trip_buses as buses
    set leader_participant_id = leader_assignment.id
    where buses.id = target_bus_id;
  end loop;

  return created_trip;
exception
  when unique_violation then
    raise exception 'An active trip already exists or the trip name is invalid.'
      using errcode = '23505';
end;
$$;

create or replace function public.claim_due_general_alarm_notifications()
returns table (
  attempt_id int8,
  expo_push_token text,
  locale text,
  platform text,
  boarding_id int8,
  participant_id int8,
  participant_code text,
  expected_status public.bus_boarding_status,
  is_urgent boolean,
  title text,
  departure_at timestamptz
)
language sql
security definer
set search_path = ''
as $$
  with due as (
    select
      boardings.id as boarding_id,
      participants.id as participant_id,
      participants.display_name as participant_code,
      devices.id as push_device_id,
      devices.expo_push_token,
      devices.locale,
      devices.platform,
      case
        when responses.id is null then 'read'::public.bus_boarding_status
        when responses.status = 'read'::public.bus_boarding_status
          then 'on_way'::public.bus_boarding_status
        else 'boarded'::public.bus_boarding_status
      end as expected_status,
      floor(
        extract(
          epoch from (
            now() - coalesce(responses.updated_at, boardings.opened_at)
          )
        ) / (boardings.reminder_interval_minutes * 60)
      )::int4 as reminder_slot,
      boardings.departure_at <= now()
        + make_interval(mins => boardings.urgent_before_minutes) as is_urgent,
      boardings.title,
      boardings.departure_at
    from public.bus_boardings as boardings
    join public.trip_participants as participants
      on participants.trip_id = boardings.trip_id
    join public.push_notification_devices as devices
      on devices.profile_id = participants.profile_id
    left join public.bus_boarding_responses as responses
      on responses.boarding_id = boardings.id
      and responses.participant_id = participants.id
    where boardings.closed_at is null
      and (
        responses.id is null
        or responses.status in (
          'read'::public.bus_boarding_status,
          'on_way'::public.bus_boarding_status
        )
      )
      and (
        responses.id is null
        or responses.updated_at
          + make_interval(mins => boardings.reminder_interval_minutes) <= now()
      )
  ),
  claimed as (
    insert into public.general_alarm_notification_attempts (
      boarding_id,
      participant_id,
      push_device_id,
      expected_status,
      reminder_slot
    )
    select
      due.boarding_id,
      due.participant_id,
      due.push_device_id,
      due.expected_status,
      due.reminder_slot
    from due
    where due.reminder_slot >= 0
    on conflict do nothing
    returning
      id,
      general_alarm_notification_attempts.boarding_id,
      general_alarm_notification_attempts.participant_id,
      general_alarm_notification_attempts.push_device_id,
      general_alarm_notification_attempts.expected_status,
      general_alarm_notification_attempts.reminder_slot
  )
  select
    claimed.id,
    due.expo_push_token,
    due.locale,
    due.platform,
    due.boarding_id,
    due.participant_id,
    due.participant_code,
    due.expected_status,
    due.is_urgent,
    due.title,
    due.departure_at
  from claimed
  join due
    on due.boarding_id = claimed.boarding_id
    and due.participant_id = claimed.participant_id
    and due.push_device_id = claimed.push_device_id
    and due.expected_status = claimed.expected_status
    and due.reminder_slot = claimed.reminder_slot;
$$;

comment on function public.claim_due_general_alarm_notifications() is
  'Claims due notifications and returns participant display names in the legacy participant_code response field.';

