create or replace function public.ensure_trip_profile_bus_assignment(
  p_trip_id int8,
  p_bus_id int8,
  p_profile_id int8,
  p_assignment_family_id int8
)
returns public.trip_participants
language plpgsql
set search_path = ''
as $$
declare
  generated_code text;
  profile_name text;
  saved_assignment public.trip_participants;
begin
  select profiles.display_name
  into profile_name
  from public.profiles as profiles
  where profiles.id = p_profile_id;

  if profile_name is null then
    raise exception 'Profile not found.' using errcode = 'P0002';
  end if;

  select participants.*
  into saved_assignment
  from public.trip_participants as participants
  where participants.trip_id = p_trip_id
    and participants.profile_id = p_profile_id
  order by participants.updated_at desc, participants.id desc
  limit 1
  for update;

  if saved_assignment.id is null then
    generated_code := upper(
      'U' || left(md5(p_trip_id::text || ':' || p_profile_id::text), 19)
    );

    insert into public.trip_participants (
      trip_id,
      bus_id,
      profile_id,
      assignment_family_id,
      participant_code,
      display_name
    )
    values (
      p_trip_id,
      p_bus_id,
      p_profile_id,
      p_assignment_family_id,
      generated_code,
      profile_name
    )
    returning * into saved_assignment;
  else
    update public.trip_participants as participants
    set
      assignment_family_id = p_assignment_family_id,
      bus_id = p_bus_id,
      display_name = profile_name
    where participants.id = saved_assignment.id
    returning participants.* into saved_assignment;
  end if;

  return saved_assignment;
end;
$$;

revoke all on function public.ensure_trip_profile_bus_assignment(int8, int8, int8, int8)
from public, anon, authenticated;

create or replace function public.admin_assign_trip_person(
