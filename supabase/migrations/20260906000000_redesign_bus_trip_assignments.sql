create or replace function public.admin_assign_trip_family(
  p_trip_id int8,
  p_bus_id int8,
  p_family_id int8
)
returns setof public.trip_participants
language plpgsql
security definer
set search_path = ''
as $$
declare
  family_profile record;
  saved_assignment public.trip_participants;
  saved_assignment_ids int8[] := '{}'::int8[];
begin
  if (select auth.uid()) is null or not (select public.is_admin()) then
    raise exception 'Admin access required.' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(2026090600);

  if not exists (
    select 1
    from public.trips as trips
    where trips.id = p_trip_id
      and trips.archived_at is null
  ) then
    raise exception 'Active trip not found.' using errcode = 'P0002';
  end if;

  if not exists (
    select 1
    from public.trip_buses as buses
    where buses.id = p_bus_id
      and buses.trip_id = p_trip_id
  ) then
    raise exception 'Bus does not belong to the active trip.' using errcode = '23503';
  end if;

  if not exists (
    select 1
    from public.account_families as families
    where families.id = p_family_id
  ) then
    raise exception 'Account family not found.' using errcode = 'P0002';
  end if;

  if not exists (
    select 1
    from public.profiles as profiles
    where profiles.family_id = p_family_id
  ) then
    raise exception 'The selected family has no accounts.' using errcode = '22023';
  end if;

  if exists (
    select 1
    from public.bus_boardings as boardings
    where boardings.trip_id = p_trip_id
      and boardings.closed_at is null
  ) then
    raise exception 'Close the active boarding before changing bus assignments.'
      using errcode = '55000';
  end if;

  if exists (
    select 1
    from public.trip_buses as buses
    join public.trip_participants as leaders
      on leaders.id = buses.leader_participant_id
    join public.profiles as profiles
      on profiles.id = leaders.profile_id
    where buses.trip_id = p_trip_id
      and buses.id <> p_bus_id
      and profiles.family_id = p_family_id
  ) then
    raise exception 'A family member leads another bus.' using errcode = '55000';
  end if;

  for family_profile in
    select profiles.id
    from public.profiles as profiles
    where profiles.family_id = p_family_id
    order by profiles.id
    for update
  loop
    select *
    into saved_assignment
    from public.ensure_trip_profile_bus_assignment(
      p_trip_id,
      p_bus_id,
      family_profile.id,
      p_family_id
    );
    saved_assignment_ids := array_append(saved_assignment_ids, saved_assignment.id);
  end loop;

  return query
  select participants.*
  from public.trip_participants as participants
  where participants.id = any(saved_assignment_ids)
  order by participants.display_name, participants.id;
end;
$$;

